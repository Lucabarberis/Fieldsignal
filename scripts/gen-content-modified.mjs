/**
 * Regenerates content/data/content-modified.ts from git.
 *
 * For each content data file, records the date of the last commit that
 * touched it — a real per-section "content last changed" signal used for
 * sitemap <lastmod>. Run after editing content data:
 *
 *   node scripts/gen-content-modified.mjs
 *
 * Runs at author time (not build/runtime) because Vercel's serverless runtime
 * has no git; baking the dates into a committed module keeps the sitemap
 * correct without depending on git being present when the sitemap renders.
 */
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";

const SECTIONS = {
  services: "content/data/services.ts",
  industries: "content/data/industries.ts",
  subniches: "content/data/industry-subniches.ts",
  clients: "content/data/clients.ts",
  complianceSubs: "content/data/compliance-subs.ts",
  alternatives: "content/data/alternatives.ts",
  compares: "content/data/compare.ts",
  useCases: "content/data/use-cases.ts",
  gtm: "content/data/gtm.ts",
  expertPages: "content/data/experts-pages.ts",
  guides: "content/data/guides.ts",
  glossary: "content/data/glossary.ts",
  platform: "content/data/platform.ts",
  regions: "content/data/regions.ts",
};

const entries = [];
for (const [key, file] of Object.entries(SECTIONS)) {
  if (!existsSync(file)) continue;
  let iso = "";
  try {
    iso = execFileSync("git", ["log", "-1", "--format=%cI", "--", file], {
      encoding: "utf8",
    }).trim();
  } catch {
    // no git / no history — skip this section (sitemap omits its lastmod)
  }
  if (iso) entries.push([key, iso.slice(0, 10)]);
}

const body = `/**
 * Real content-modification dates for the data-driven routes, taken from the
 * git last-commit date of each content file. Generated by
 * scripts/gen-content-modified.mjs — regenerate after editing content data.
 *
 * Used for sitemap <lastmod>. A real per-section signal beats a uniform deploy
 * timestamp (which teaches crawlers to distrust the field) and beats omitting
 * it entirely. Dates reflect the last committed change to each section's data.
 */
export const CONTENT_MODIFIED: Record<string, string> = {
${entries.map(([k, v]) => `  ${k}: "${v}",`).join("\n")}
};
`;

writeFileSync("content/data/content-modified.ts", body);
console.log(`wrote content/data/content-modified.ts (${entries.length} sections)`);
